class Operators {
    public static void main(String[] args){
        int a = 10;
        int b=20;
        System.out.println(~a);
        boolean ans =true;
        System.out.println(!ans);
        System.out.println(3&6);
        System.out.println(5|6);
        int max=(a>b)?a:b;//ternary operator
        System.out.println(max);
    }
}